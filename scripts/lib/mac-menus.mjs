// The macOS app's native menus, generated from the editor's menu definition
// (packages/editor/src/editor-menu.ts): every entry's command, English label, section, group and
// availability, plus German titles from the core i18n catalogue. Main.swift builds its File, Edit,
// View and Object menus (and the submenus for the exact, fastening, drawing and tools sections)
// from this table, so a command added to the definition appears natively with no Swift change.
const swift=value=>'"'+String(value).replace(/\\/g,'\\\\').replace(/"/g,'\\"').replace(/\n/g,'\\n')+'"';
/**
 * @param {{editorMenu:readonly {command:string;label:string;section:string;group:number;requires?:string;exact?:true}[];editorMenuSections:Readonly<Record<string,string>>;german:(key:string)=>string}} input
 * @returns {string} the Swift source of apps/macos/EditorMenu.generated.swift
 */
export function macMenuSwift({editorMenu,editorMenuSections,german}){
 const keys=[...new Set([...Object.values(editorMenuSections),...editorMenu.map(item=>item.label)])];
 const lines=[
  '// SPDX-License-Identifier: BSD-3-Clause',
  '// Generated by scripts/generate-mac-menus.mjs from packages/editor/src/editor-menu.ts.',
  '// Do not edit: run `node scripts/generate-mac-menus.mjs` (part of `npm run mac:build`).',
  '',
  'struct EditorMenuEntry {',
  '    let command: String',
  '    /// English title, also the localization key.',
  '    let label: String',
  '    let section: String',
  '    let group: Int',
  '    /// Editor state that enables the item, or nil when it always is.',
  '    let requires: String?',
  '    /// Loads the exact B-rep kernel on first use.',
  '    let exact: Bool',
  '}',
  '',
  'let editorMenuEntries: [EditorMenuEntry] = [',
  ...editorMenu.map(item=>`    EditorMenuEntry(command: ${swift(item.command)}, label: ${swift(item.label)}, section: ${swift(item.section)}, group: ${item.group}, requires: ${item.requires?swift(item.requires):'nil'}, exact: ${item.exact?'true':'false'}),`),
  ']',
  '',
  '/// Section titles (English, also the localization key), in definition order.',
  'let editorMenuSectionOrder: [String] = ['+Object.keys(editorMenuSections).map(swift).join(', ')+']',
  'let editorMenuSectionTitles: [String: String] = [',
  ...Object.entries(editorMenuSections).map(([key,title])=>`    ${swift(key)}: ${swift(title)},`),
  ']',
  '',
  '/// German titles of the labels and sections above (from packages/core/src/locales).',
  'let editorMenuGerman: [String: String] = [',
  ...keys.filter(key=>german(key)!==key).map(key=>`    ${swift(key)}: ${swift(german(key))},`),
  ']',
  '',
 ];
 return lines.join('\n');
}

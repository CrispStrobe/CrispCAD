import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {readPortableHistory} from '@brickwright/cad-history';

test('create and re-edit a revolved shaft, validate the axis, undo and reopen',async({page,hasTouch},info)=>{
 const press=(control:ReturnType<typeof page.getByRole>)=>hasTouch?control.tap():control.click();
 await page.goto('/');
 const root=page.locator('#cad-root');
 const ready=()=>expect(root).toHaveAttribute('data-state','ready');
 await ready();
 await press(page.locator('summary[aria-label="More sketch tools"]'));
 await press(page.getByRole('button',{name:'Revolve',exact:true}));
 const dialog=page.getByRole('dialog',{name:'Sketch and revolution'});
 await press(dialog.getByRole('button',{name:'About sketching and revolution'}));
 await expect(dialog).toContainText('The dashed line marks the axis.');
 await press(dialog.getByRole('button',{name:'About sketching and revolution'}));
 await dialog.getByLabel('Sketch name').fill('Shaft profile');
 await dialog.getByLabel('Sketch width (mm)').fill('10');
 await dialog.getByLabel('Sketch plane').selectOption('XZ');
 await expect(dialog.locator('.sketch-revolution-axis')).toHaveAttribute('x1','-5');
 const axis=dialog.getByLabel('Axis X in sketch (mm)'),auto=dialog.getByLabel('Use left edge of profile');
 await auto.uncheck();
 await axis.fill('0');
 await expect(dialog.getByRole('status',{name:'Sketch status'})).toContainText('stay on one side');
 const create=dialog.getByRole('button',{name:'Create revolution'});
 await expect(create).toBeDisabled();
 await auto.check();
 await press(create);
 await expect(dialog).toBeHidden();
 await ready();
 const full=Number(await root.getAttribute('data-triangles'));
 expect(full).toBeGreaterThan(128);

 const edit=page.getByRole('button',{name:'Edit sketch & revolution'});
 if(!await edit.isVisible())await press(page.getByRole('button',{name:'Properties',exact:true}));
 await press(edit);
 const sweep=dialog.getByLabel('Sweep angle (deg)');
 await sweep.fill('90');
 await dialog.getByLabel('Sketch depth (mm)').fill('24');
 await expect(dialog.getByLabel('Sketch preview')).toContainText('90° sweep');
 await press(dialog.getByRole('button',{name:'Apply sketch changes'}));
 await expect(dialog).toBeHidden();
 await ready();
 await expect.poll(async()=>Number(await root.getAttribute('data-triangles'))).toBeLessThan(full);
 const undo=page.getByRole('button',{name:'Undo',exact:true});
 await press(undo);
 await ready();
 await expect(root).toHaveAttribute('data-triangles',String(full));
 await press(page.getByRole('button',{name:'Redo',exact:true}));
 await ready();

 const [download]=await Promise.all([page.waitForEvent('download'),press(page.getByRole('button',{name:'Save project file',exact:true}))]);
 const project=info.outputPath('shaft.bcad');
 await download.saveAs(project);
 const history=await readPortableHistory(await readFile(project));
 const saved=history.readDocument(history.project.headId);
 const node=saved.nodes[saved.roots[0]];
 if(node.kind!=='revolution')throw Error('Expected the saved revolution');
 const sketchId=node.sketchId;
 expect(node.angle).toBe(90);
 expect(saved.sketches[sketchId].profile).toMatchObject({width:10,depth:24});
 await press(page.getByRole('button',{name:'New project',exact:true}));
 await expect(page.getByTestId('object-name')).toHaveCount(0);
 const chooser=page.waitForEvent('filechooser');
 await press(page.getByRole('button',{name:'Open project',exact:true}));
 await (await chooser).setFiles(project);
 await ready();
 await press(page.getByTestId('object-name').filter({hasText:'Revolution'}));
 if(!await edit.isVisible())await press(page.getByRole('button',{name:'Properties',exact:true}));
 await press(edit);
 await expect(sweep).toHaveValue('90');
 await expect(dialog.getByLabel('Sketch depth (mm)')).toHaveValue('24');
});

import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('a linked sheet follows its sketch and survives reopen, source removal, and Undo',async({page})=>{
 await page.goto('/');
 const ready=()=>expect(page.locator('#cad-root')).toHaveAttribute('data-state','ready');
 await ready();
 const openParameters=page.getByRole('button',{name:'Parameters',exact:true});
 const parameters=page.getByRole('dialog',{name:'Model parameters'});
 const spacing=parameters.getByLabel('Parameter expression',{exact:true});
 await openParameters.click();
 await parameters.getByRole('button',{name:'Add parameter'}).click();
 await parameters.getByLabel('Parameter name',{exact:true}).fill('spacing');
 await spacing.fill('20');
 const applyParameters=parameters.getByRole('button',{name:'Apply parameters'});
 const closeParameters=parameters.getByRole('button',{name:'Close parameters'});
 await applyParameters.click();
 await closeParameters.click();

 await page.getByRole('button',{name:'Sketch',exact:true}).click();
 const sketch=page.getByRole('dialog',{name:'Sketch and extrusion'});
 await sketch.getByLabel('Profile',{exact:true}).selectOption('region');
 await sketch.getByLabel('Region loops (mm)').fill('0, 0 | 40, 0 | 40, 30 | 0, 30\nCIRCLE 20 mm - spacing / 2, 15, 2\nCIRCLE 20 mm + spacing / 2, 15, 3');
 await sketch.getByRole('button',{name:'Create extrusion'}).click();
 await ready();

 const create=page.getByRole('button',{name:'Create drawing sheet',exact:true});
 if(!await create.isVisible())await page.getByRole('button',{name:'Properties',exact:true}).click();
 await create.click();
 const dialog=page.getByRole('dialog',{name:'Drawing sheet',exact:true});
 const preview=dialog.getByRole('img',{name:'Drawing preview'});
 const drawingCircles=preview.locator('circle');
 const holeSpacing=()=>drawingCircles.evaluateAll(circles=>Math.abs(Number(circles[1].getAttribute('cx'))-Number(circles[0].getAttribute('cx'))));
 const title=dialog.getByLabel('Sheet title');
 const scale=dialog.getByLabel('Drawing scale');
 const hidden=dialog.getByLabel('Show hidden lines');
 const closeDrawing=dialog.getByRole('button',{name:'Close drawing',exact:true});
 const save=dialog.getByRole('button',{name:'Save drawing sheet',exact:true});
 await title.fill('Motor plate drawing');
 const showSection=dialog.getByRole('checkbox',{name:'Show section A-A'});
 const cut=dialog.getByLabel('Section position (mm)');
 await showSection.check();
 await expect(cut).toHaveValue('15');
 await expect(preview).toContainText('Section A-A');
 await expect(preview.locator('.drawing-section')).toHaveCount(3);
 await expect(preview.locator('.drawing-hatch').first()).toBeVisible();
 await cut.fill('50');
 await expect(dialog.getByRole('status',{name:'Drawing status'})).toContainText('misses the part');
 await expect(save).toBeDisabled();
 await cut.fill('15');
 await expect(preview).toContainText('Front view');
 await expect(preview).toContainText('Right view');
 await expect(preview).toContainText('Top view');
 await expect(preview.locator('.drawing-hidden')).toHaveCount(8);
 expect(await holeSpacing()).toBe(20);
 await save.click();
 await expect(dialog).toBeHidden();

 const sheet=page.getByRole('button',{name:'Drawing: Motor plate drawing',exact:true});
 if(!await sheet.isVisible())await page.getByRole('button',{name:'Objects',exact:true}).click();
 await expect(sheet).toBeVisible();
 await openParameters.click();
 await spacing.fill('28');
 await applyParameters.click();
 await closeParameters.click();
 await ready();
 await sheet.click();
 expect(await holeSpacing()).toBe(28);
 await scale.selectOption('2:1');
 expect(await holeSpacing()).toBe(56);
 await hidden.uncheck();
 await expect(preview.locator('.drawing-hidden')).toHaveCount(0);
 const [download]=await Promise.all([page.waitForEvent('download'),dialog.getByRole('button',{name:'Export drawing PDF'}).click()]);
 const path=await download.path();
 if(!path)throw Error('Expected a local PDF');
 const pdf=await readFile(path,'utf8');
 expect(pdf).toContain('/MediaBox [0 0 841.88976 595.27559]');
 expect(pdf).toContain('229 14 m 279 14 l');
 expect(pdf).not.toContain('[1.4 0.9] 0 d');
 expect(pdf).toContain('[3.5 1 0.7 1] 0 d');
 await save.click();
 await expect(dialog).toBeHidden();

 await page.reload();
 await ready();
 if(!await sheet.isVisible())await page.getByRole('button',{name:'Objects',exact:true}).click();
 await sheet.click();
 await expect(scale).toHaveValue('2:1');
 await expect(showSection).toBeChecked();
 await expect(cut).toHaveValue('15');
 await expect(preview.locator('.drawing-section')).toHaveCount(3);
 await expect(hidden).not.toBeChecked();
 expect(await holeSpacing()).toBe(56);
 await closeDrawing.click();
 await page.getByTestId('object-name').click();
 await page.keyboard.press('Backspace');
 await expect(page.getByTestId('object-name')).toHaveCount(0);
 await sheet.click();
 await expect(dialog.getByRole('status',{name:'Drawing status'})).toContainText('Drawing source unavailable');
 await expect(save).toBeDisabled();
 await closeDrawing.click();
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 await ready();
 await sheet.click();
 await expect(preview).toBeVisible();
 expect(await holeSpacing()).toBe(56);
 await closeDrawing.click();
 await page.getByTestId('object-name').click();
 if(!await create.isVisible())await page.getByRole('button',{name:'Properties',exact:true}).click();
 await create.click();
 await title.fill('Motor plate overview');
 await scale.selectOption('1:2');
 await save.click();
 const [set]=await Promise.all([
  page.waitForEvent('download'),page.getByRole('button',{name:'Export drawing set (PDF)',exact:true}).click()
 ]);
 const setPath=await set.path();
 if(!setPath)throw Error('Expected the drawing set PDF');
 const drawingSet=await readFile(setPath,'utf8');
 expect(drawingSet).toContain('/Type /Pages /Count 2');
 expect(drawingSet).toContain(Buffer.from('Sheet 1 of 2','latin1').toString('hex'));
 expect(drawingSet).toContain(Buffer.from('Sheet 2 of 2','latin1').toString('hex'));
});
